export function isAllowedForTrack(materialTitle: string, studentTrack: string): boolean {
  if (!studentTrack) return true;
  const title = (materialTitle || '').toLowerCase();
  
  // لو الطالب أدبي، امنع فيزياء وكيمياء وأحياء ورياضة ودبلومات نهائي
  if (studentTrack.includes('أدبي')) {
    if (["فيزياء", "كيمياء", "أحياء", "جيولوجيا", "رياضة", "تفاضل", "تكامل", "استاتيكا", "ديناميكا", "physics", "chemistry", "biology", "محاسبة", "ادارة", "تجاري", "رسم فني", "ميكانيكا", "كهرباء", "صناعي"].some(k => title.includes(k.toLowerCase()))) {
      return false;
    }
    return true;
  }

  // لو علمي علوم، امنع أدبي ورياضة ودبلومات
  if (studentTrack.includes('علمي علوم')) {
    if (["تاريخ", "جغرافيا", "فلسفة", "منطق", "علم نفس", "اجتماع", "استاتيكا", "ديناميكا", "تفاضل", "تكامل", "جبر", "رياضة", "محاسبة", "ادارة", "تجاري", "رسم فني", "ميكانيكا", "كهرباء", "صناعي"].some(k => title.includes(k.toLowerCase()))) {
      return false;
    }
    return true;
  }

  // لو علمي رياضة، امنع أحياء وجيولوجيا وأدبي ودبلومات
  if (studentTrack.includes('علمي رياضة')) {
    if (["أحياء", "جيولوجيا", "تاريخ", "جغرافيا", "فلسفة", "منطق", "علم نفس", "اجتماع", "biology", "geology", "محاسبة", "ادارة", "تجاري", "رسم فني", "ميكانيكا", "كهرباء", "صناعي"].some(k => title.includes(k.toLowerCase()))) {
      return false;
    }
    return true;
  }

  // لو دبلوم تجارة، امنع مواد علمي وأدبي وصنايع
  if (studentTrack.includes('تجارة')) {
    if (["فيزياء", "كيمياء", "أحياء", "جيولوجيا", "تاريخ", "جغرافيا", "فلسفة", "منطق", "علم نفس", "رسم فني", "ميكانيكا", "تبريد", "صناعي"].some(k => title.includes(k.toLowerCase()))) {
      return false;
    }
    return true;
  }

  // لو دبلوم صنايع، امنع مواد علمي وأدبي وتجارة
  if (studentTrack.includes('صنايع')) {
    if (["فيزياء", "كيمياء", "أحياء", "جيولوجيا", "تاريخ", "جغرافيا", "فلسفة", "منطق", "علم نفس", "محاسبة", "تسويق", "ادارة", "تجاري"].some(k => title.includes(k.toLowerCase()))) {
      return false;
    }
    return true;
  }

  // لو دورات ICDL وجامعات
  if (studentTrack.includes('ICDL')) {
    if (["فيزياء", "كيمياء", "أحياء", "جيولوجيا", "تاريخ", "جغرافيا", "فلسفة", "منطق", "علم نفس", "رسم فني", "ميكانيكا", "محاسبة"].some(k => title.includes(k.toLowerCase()))) {
      return false;
    }
    return true;
  }

  return true;
}
