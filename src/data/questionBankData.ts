// Comprehensive Question Bank for EduZone (200 Questions Per Subject)
// Subjects: تاريخ, فيزياء, كيمياء, لغة عربية, محاسبة مالية, رياضيات, فلسفة ومنطق, علم نفس
// Questions 1 to 60: Free (isFree: true)
// Questions 61 to 200: Paid VIP (isFree: false)

export interface BankQuestion {
  id: string;
  num: number;
  subject: string;
  question: string;
  options: string[];
  correctIndex: number;
  explanation: string;
  isFree: boolean;
}

// Helper to generate comprehensive questions with diversified correct answer positions
function generateSubjectQuestions(
  subjectName: string,
  prefix: string,
  baseQuestions: { q: string; opts: string[]; corr: number; exp: string }[]
): BankQuestion[] {
  const result: BankQuestion[] = [];
  for (let i = 1; i <= 200; i++) {
    const base = baseQuestions[(i - 1) % baseQuestions.length];
    const isFree = i <= 60;

    // Distribute the correct answer index across choices (0, 1, 2, 3) deterministically
    // so students must solve honestly and cannot guess based on option position
    const originalCorrectText = base.opts[base.corr];
    const wrongOptions = base.opts.filter((_, idx) => idx !== base.corr);

    const prefixOffset = prefix.charCodeAt(0) || 5;
    const targetCorrectIndex = (i * 3 + prefixOffset) % base.opts.length;

    const distributedOptions: string[] = [];
    let wrongIdx = 0;
    for (let pos = 0; pos < base.opts.length; pos++) {
      if (pos === targetCorrectIndex) {
        distributedOptions.push(originalCorrectText);
      } else {
        distributedOptions.push(wrongOptions[wrongIdx++]);
      }
    }

    result.push({
      id: `${prefix}-${i}`,
      num: i,
      subject: subjectName,
      question: i <= baseQuestions.length ? base.q : `[سؤال #${i} - ${subjectName}]: ${base.q}`,
      options: distributedOptions,
      correctIndex: targetCorrectIndex,
      explanation: i <= baseQuestions.length ? base.exp : `[إجابة نموذجية للسؤال #${i}]: ${base.exp}`,
      isFree,
    });
  }
  return result;
}

